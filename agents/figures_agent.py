"""Regenerate canonical figures and the incomplete-source to provisional bridge."""
import json
from pathlib import Path

import pandas as pd
from commentary_facts import build_facts


def main():
    facts=build_facts()
    vt=pd.read_csv('output/variance_table.csv')
    y=vt[vt.month.str.startswith('2025')]
    sign=y.line_item.map(lambda line: 1 if line=='Net billings' else -1)
    # Available-only subtotal is explicitly incomplete; missing amounts are not confirmed zeros.
    subtotal=(y.actual*sign).sum()
    proposed=(y.provisional_actual*sign).sum()
    placeholder=((-y.actual+y.provisional_actual)*sign).where(y.withheld_from_analysis,0).sum()
    missing=proposed-subtotal-placeholder
    bridge=pd.DataFrame([
        dict(component='Available source subtotal (incomplete; not a confirmed operating result)',amount=round(subtotal,2)),
        dict(component='Unapproved billings placeholder effect',amount=round(placeholder,2)),
        dict(component='Unapproved missing-actual estimates',amount=round(missing,2)),
        dict(component='Provisional demonstration operating result',amount=round(proposed,2))])
    bridge.to_csv('output/reporting_bridge.csv',index=False)
    section=['## FY2025 available-source to provisional bridge','',
             'The available-source subtotal excludes missing actuals and includes an unverified billings amount. It is incomplete and must not be treated as a confirmed result. Estimates are unapproved.','',
             '| Component | EUR |','|---|---|']
    section += [f"| {r.component} | {r.amount:,.2f} |" for r in bridge.itertuples()]
    report=Path('output/data_quality_report.md')
    report.write_text(report.read_text(encoding='utf-8').split('## FY2025 available-source to provisional bridge')[0].rstrip()+'\n\n'+'\n'.join(section)+'\n',encoding='utf-8')
    lines=['# Canonical figures','', 'Synthetic case study, as of 30 June 2026. All amounts are EUR. Source actuals and budgets remain in variance_table.csv beside separate provisional columns.','',
           'Generated by agents/figures_agent.py; changes to the input require regeneration. Financial statements below use the optional unapproved provisional scenario.','',
           '| Business unit | Period | Metric | Signed amount | Evidence |','|---|---|---|---|---|']
    lines += [f"| {f['business_unit']} | {f['period']} | {f['metric']} | {f['amount']:,.2f} | {', '.join(f['evidence'])} |" for f in facts if f['amount'] is not None]
    lines += ['', '## Reporting assumptions', '', *[f['statement']+'\n' for f in facts if f['amount'] is None], '',
              'Net billings are invoiced amounts; the sample does not implement accounting revenue recognition. See output/reporting_adjustments.csv for cell estimates, output/forecast_adjustments.csv for recurrence decisions and output/forecast_backtest.csv for historical predictions.','']
    Path('FIGURES.md').write_text('\n'.join(lines),encoding='utf-8')
    print('Canonical figures and source-to-provisional bridge regenerated')


if __name__=='__main__':
    main()
